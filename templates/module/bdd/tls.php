        <h3 class="text-2xl font-extrabold tracking-wide mb-4 drop-shadow-md">🔐 Présentation de TLS</h3>

        <p class="text-cyan-200 leading-relaxed mb-4 drop-shadow-sm text-sm">
            <strong>Transport Layer Security (TLS)</strong> est un protocole essentiel qui garantit la sécurité des échanges sur Internet. Il protège la confidentialité, l'intégrité et l'authenticité des données transmises entre un client et un serveur.
        </p>

